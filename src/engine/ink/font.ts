/** Advance widths in em (default 0.74). */
const ADVANCE: Record<string, number> = { '1': 0.56, '.': 0.3, ',': 0.3, ':': 0.3, '-': 0.62, ' ': 0.46, '°': 0.36, I: 0.6, l: 0.5, i: 0.5, M: 0.8, W: 0.8, m: 0.8, '(': 0.5, ')': 0.5 };

export type GlyphStroke = readonly (readonly [number, number])[];

const cache = new Map<string, GlyphStroke[]>();

function parse(raw: string): GlyphStroke[] {
  return raw.split('|').map((s) => s.trim().split(/\s+/).map((p) => {
    const [x, y] = p.split(',').map(Number);
    return [(x ?? 0) / 10, (y ?? 0) / 10] as const;
  }));
}

/** Strokes of a character in em units (x right, y up, baseline 0), and its advance. Unknown characters: none. */
export function glyph(ch: string): { strokes: GlyphStroke[]; advance: number } {
  let raw = RAW[ch];
  let scale = 1;
  if (raw === undefined && ch >= 'a' && ch <= 'z') {
    raw = RAW[ch.toUpperCase()];
    scale = 0.72;
  }
  const key = ch;
  let strokes = cache.get(key);
  if (!strokes) {
    strokes = raw ? parse(raw).map((st) => st.map(([x, y]) => [x * scale, y * scale] as const)) : [];
    cache.set(key, strokes);
  }
  const adv = (ADVANCE[ch] ?? 0.74) * (scale < 1 ? 0.85 : 1);
  return { strokes, advance: adv };
}

/** Width of a text run in em. */
export function textWidth(text: string): number {
  let w = 0;
  for (const ch of text) w += glyph(ch).advance;
  return w;
}

